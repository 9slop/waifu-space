const GLYPH_RE =
  /(\p{Extended_Pictographic}\uFE0F?|[\u2600-\u27BF])/gu;

function normalizeGlyph(glyph: string): string {
  return glyph.replace(/\uFE0F/g, '');
}

function FallbackGlyph(props: { class?: string; children?: JSX.Element }) {
  return <span class={props.class}>{props.children}</span>;
}

/** Renders an emoji glyph string as the mapped Phosphor icon (1em, currentColor). */
export function EmojiIcon(props: { glyph?: string; class?: string }) {
  const key = () => normalizeGlyph(props.glyph ?? '');
  const render = () => {
    const Comp = EMOJI_ICONS[key()] ?? FallbackGlyph;
    return <Comp class={props.class}>{props.glyph}</Comp>;
  };
  return <span class={props.class}>{render()}</span>;
}

/** Splits a text run into plain-text and emoji segments. */
export function splitGlyphs(text: string): Array<{ text: string; emoji: boolean }> {
  const segments: Array<{ text: string; emoji: boolean }> = [];
  let last = 0;
  for (const match of text.matchAll(GLYPH_RE)) {
    const idx = match.index ?? 0;
    if (idx > last) segments.push({ text: text.slice(last, idx), emoji: false });
    segments.push({ text: match[0], emoji: true });
    last = idx + match[0].length;
  }
  if (last < text.length) segments.push({ text: text.slice(last), emoji: false });
  return segments;
}

/** Renders text, converting emoji runs into Phosphor icons; unmapped glyphs fall back to the raw emoji. */
export function GlyphText(props: { text: string; class?: string }) {
  return (
    <span class={props.class}>
      {splitGlyphs(props.text).map(seg =>
        seg.emoji
          ? <EmojiIcon glyph={seg.text} />
          : <span>{seg.text}</span>
      )}
    </span>
  );
}
